#!/usr/bin/env python3
"""Install this repo's skills, agents and commands into a project, in the layout a coding harness reads.

Usage:
  scripts/install-harness.py <project-dir> <harness>   install into an existing project folder
  scripts/install-harness.py --list                     print each harness id and name
  scripts/install-harness.py --validate <harness>       exit 1 unless <harness> is known

Standard library only. scripts/new-project.sh calls it for --harness. The layout per harness is
data/harnesses.json; the sources are agents/, commands/ and skills/ as they are on disk, so run
scripts/build-agents.py first if you changed the data they are generated from.

Every file is written under <project-dir>: skills, agents and commands in the harness's project
folders, any extra project files the harness needs, and, in the shared folder named in the data,
a licence notice, a copy of LICENSE-CONTENT and the agents and commands reference pages. Nothing
is written to a user or global configuration folder. The installer refuses to overwrite a file.

The installed files stay under CC BY-SA 4.0, like their sources: each keeps a provenance comment
pointing at the notice, and each skill keeps its SOURCES.md.
"""
import json
import os
import posixpath
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
REPO_URL = "https://github.com/mitulamin/ai-sdlc-loop"
SCHEMA_VERSION = "1.0.0"
MARKER_PREFIX = "<!-- GENERATED by scripts/build-agents.py"
PROVENANCE = "<!-- Installed from ai-sdlc-loop"
EXTERNAL = re.compile(r"^([a-z][a-z0-9+.-]*:|//|#)", re.I)
# A markdown link target, or a bare ../ path in prose (such as "see ../../LICENSE-CONTENT").
LINK_OR_PATH = re.compile(r"(\]\()([^)\s]+)(\))|(?<![\w/.(\]-])((?:\.\./)+[\w./-]*\w)")
YAML_PLAIN = re.compile(r"[A-Za-z][A-Za-z0-9_.-]*")
YAML_RESERVED = {"true", "false", "yes", "no", "on", "off", "null", "~"}


def load_harnesses():
    doc = json.loads((DATA / "harnesses.json").read_text(encoding="utf-8"))
    if doc.get("schema_version") != SCHEMA_VERSION:
        raise SystemExit(f"data/harnesses.json: schema_version is {doc.get('schema_version')!r}, this script expects {SCHEMA_VERSION}")
    return doc


def parse_front(text):
    """Split '---' front matter from the body. Values are JSON where they parse, else plain strings."""
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        return {}, text
    end = text.index("\n---\n", 4)
    front = {}
    for line in text[4:end].splitlines():
        key, sep, value = line.partition(":")
        if not sep:
            continue
        value = value.strip()
        try:
            front[key.strip()] = json.loads(value)
        except json.JSONDecodeError:
            front[key.strip()] = value
    return front, text[end + 5:]


def yaml_scalar(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    v = str(v)
    if YAML_PLAIN.fullmatch(v) and v.lower() not in YAML_RESERVED:
        return v
    return json.dumps(v, ensure_ascii=False)


def yaml_entry(key, v):
    if isinstance(v, dict):
        return [f"{key}:"] + [f"  {k}: {yaml_scalar(x)}" for k, x in v.items()]
    if isinstance(v, list) and v and all(isinstance(x, dict) for x in v):
        lines = [f"{key}:"]
        for item in v:
            for i, (k, x) in enumerate(item.items()):
                lines.append(f"{'  - ' if i == 0 else '    '}{k}: {yaml_scalar(x)}")
        return lines
    if isinstance(v, list):
        return [f"{key}: [" + ", ".join(json.dumps(x, ensure_ascii=False) for x in v) + "]"]
    return [f"{key}: {yaml_scalar(v)}"]


def git_ref():
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True, check=True)
        return out.stdout.strip() or "main"
    except (OSError, subprocess.CalledProcessError):
        return "main"


class Item:
    """One source file to install: a skill, an agent or a command."""

    def __init__(self, kind, src, dest, front, body, values, role=None):
        self.kind, self.src, self.dest = kind, src, dest
        self.front, self.body, self.values, self.role = front, body, values, role


class Installer:
    def __init__(self, harness_id):
        self.doc = load_harnesses()
        by_id = {h["id"]: h for h in self.doc["harnesses"]}
        if harness_id not in by_id:
            raise SystemExit(f"Unknown harness: {harness_id}. Known: none, {', '.join(by_id)}")
        self.h = by_id[harness_id]
        self.shared = self.doc["shared_dir"]
        self.ref = git_ref()
        self.items = []
        self.pathmap = {}
        self.commands = sorted(p.stem for p in (ROOT / "commands").glob("*.md") if p.name != "README.md")
        self._collect()

    def cmd_name(self, name):
        return self.h["commands"]["prefix"] + name

    def _collect(self):
        h = self.h
        smap = json.loads((DATA / "skill-principle-map.json").read_text(encoding="utf-8"))
        for e in sorted(smap["skills"], key=lambda e: e["slot"]):
            src = f"{e['folder']}/SKILL.md"
            front, body = parse_front((ROOT / src).read_text(encoding="utf-8"))
            skill_dir = f"{h['skills']['dir']}/{front['name']}"
            meta = {"source": src}
            for k, v in front.items():
                if k not in ("name", "description", "licence") and v not in ([], ""):
                    meta[k] = ", ".join(v) if isinstance(v, list) else str(v)
            values = {"name": front["name"], "description": front["description"], "licence": front.get("licence"), "metadata": meta}
            self.items.append(Item("skill", src, f"{skill_dir}/SKILL.md", front, body, values))
            self.pathmap[src] = f"{skill_dir}/SKILL.md"
            self.pathmap[e["folder"]] = skill_dir
            sources = f"{e['folder']}/SOURCES.md"
            if (ROOT / sources).exists():
                self.items.append(Item("skill-sources", sources, f"{skill_dir}/SOURCES.md", {}, (ROOT / sources).read_text(encoding="utf-8"), {}))
                self.pathmap[sources] = f"{skill_dir}/SOURCES.md"
            for pid in [e["principle_id"]] + e.get("aliases", []):
                self.pathmap[f"principles/{pid}.md"] = f"{skill_dir}/SKILL.md"
        for path in sorted((ROOT / "agents").glob("*.md")):
            src = f"agents/{path.name}"
            front, body = parse_front(path.read_text(encoding="utf-8"))
            if path.name == "README.md":
                dest = f"{self.shared}/agents.md"
                self.items.append(Item("reference", src, dest, {}, body, {}))
            else:
                name = front["name"]
                dest = f"{h['agents']['dir']}/{h['agents']['file'].format(name=name)}"
                values = {"name": name, "description": front["description"], "tools": front.get("tools")}
                self.items.append(Item("agent", src, dest, front, body, values, role=front.get("role")))
            self.pathmap[src] = dest
        for path in sorted((ROOT / "commands").glob("*.md")):
            src = f"commands/{path.name}"
            front, body = parse_front(path.read_text(encoding="utf-8"))
            if path.name == "README.md":
                dest = f"{self.shared}/commands.md"
                self.items.append(Item("reference", src, dest, {}, body, {}))
            else:
                name = self.cmd_name(path.stem)
                dest = f"{h['commands']['dir']}/{h['commands']['file'].format(name=name)}"
                values = {"name": name, "description": front["description"], "argument-hint": front.get("argument-hint")}
                self.items.append(Item("command", src, dest, front, body, values))
            self.pathmap[src] = dest
        self.pathmap["LICENSE-CONTENT"] = f"{self.shared}/LICENSE-CONTENT"
        self.pathmap["NOTICE.md"] = f"{self.shared}/NOTICE.md"
        coord = next((i for i in self.items if i.kind == "agent" and i.role == "coordinator"), None)
        if coord is None:
            raise SystemExit("agents/: no agent with role coordinator")
        self.coordinator = coord.dest

    def front_matter(self, item, spec):
        lines = []
        for entry in spec:
            if "roles" in entry and item.role not in entry["roles"]:
                continue
            if "value" in entry:
                lines += yaml_entry(entry["key"], entry["value"])
                continue
            v = item.values.get(entry["from"])
            if v in (None, "", [], {}):
                continue
            if entry["from"] == "tools":
                v = self.tools_value(v, entry.get("format", "list"))
                if not v:
                    continue
            lines += yaml_entry(entry["key"], v)
        return ["---"] + lines + ["---"] if lines else []

    def tools_value(self, tools, fmt):
        names = self.h["agents"].get("tool_names", {})
        missing = [t for t in tools if t not in names]
        if missing:
            raise SystemExit(f"data/harnesses.json: {self.h['id']} has no tool_names entry for {', '.join(missing)}")
        mapped = list(dict.fromkeys(n for t in tools for n in names[t]))
        if fmt == "csv":
            return ", ".join(mapped)
        if fmt == "deny-rules":
            every = dict.fromkeys(n for ns in names.values() for n in ns)
            return [{"action": a, "resource": "*", "effect": "deny"} for a in every if a not in mapped]
        return mapped

    def rewrite(self, text, src, dest):
        """Point links at the installed copies, or at this repo on GitHub, and prefix command names."""
        src_dir, dest_dir = posixpath.dirname(src), posixpath.dirname(dest)

        def target(t):
            if EXTERNAL.match(t):
                return t
            path, hash_, frag = t.partition("#")
            if not path:
                return t
            full = posixpath.normpath(posixpath.join(src_dir, path))
            if full.startswith(".."):
                return t
            if full in self.pathmap:
                return posixpath.relpath(self.pathmap[full], dest_dir or ".") + hash_ + frag
            if (ROOT / full).exists():
                kind = "tree" if (ROOT / full).is_dir() else "blob"
                return f"{REPO_URL}/{kind}/{self.ref}/{full}" + hash_ + frag
            return t

        def sub(m):
            if m.group(1):
                return m.group(1) + target(m.group(2)) + m.group(3)
            return target(m.group(4))

        text = LINK_OR_PATH.sub(sub, text)
        if self.commands and self.h["commands"]["prefix"]:
            names = "|".join(re.escape(c) for c in self.commands)
            text = re.sub(rf"(?<![\w/.-])/({names})(?![\w-])", lambda m: "/" + self.cmd_name(m.group(1)), text)
        return text

    def provenance(self, item):
        return (f"{PROVENANCE} {item.src} at {self.ref[:12]} by scripts/new-project.sh, adapted for {self.h['name']} "
                f"(front matter, links and command names). CC BY-SA 4.0: see {self.shared}/NOTICE.md. -->")

    def render(self, item):
        body = item.body
        lines = body.split("\n")
        if lines and lines[0].startswith(MARKER_PREFIX):
            lines = lines[1:]
        body = "\n".join(lines).lstrip("\n")
        if item.kind == "command":
            c = self.h["commands"]
            if c["arguments"] is not None:
                body = body.replace("$ARGUMENTS", c["arguments"])
            if c["preamble"]:
                body = c["preamble"].replace("{coordinator}", self.coordinator) + "\n\n" + body
        body = self.rewrite(body, item.src, item.dest)
        spec = {"skill": self.h["skills"]["front_matter"], "agent": self.h["agents"]["front_matter"],
                "command": self.h["commands"]["front_matter"]}.get(item.kind, [])
        head = self.front_matter(item, spec)
        return "\n".join(head + [self.provenance(item), "", body.rstrip("\n")]) + "\n"

    def notice(self):
        h, ref = self.h, self.ref
        roots = sorted({h[k]["dir"] for k in ("skills", "agents", "commands")})
        extras = ", ".join(f"`{e['path']}`" for e in h["extra_files"])
        lines = [
            "# Notice for the AI SDLC Loop files in this project", "",
            f"This project was created with `scripts/new-project.sh` from [AI SDLC Loop]({REPO_URL}) at commit `{ref}`, with the {h['name']} harness.", "",
            "The project is under the MIT licence in `LICENSE`, except for the files described here. They are copied and adapted from "
            "AI SDLC Loop's skills, agents and commands, and they stay under the Creative Commons Attribution-ShareAlike 4.0 International "
            "licence (CC BY-SA 4.0), like their sources. The licence text is in [LICENSE-CONTENT](LICENSE-CONTENT) next to this file, and at "
            "https://creativecommons.org/licenses/by-sa/4.0/.", "",
            f"Attribution: {self.doc['attribution']}, {REPO_URL}. Sources at {REPO_URL}/tree/{ref}.", "",
            f"Changes from the sources: front matter converted to the format {h['name']} reads, links pointed at the installed copies or at "
            "the source repo, loop command names given a prefix, and a provenance comment added to each file. The text is otherwise unchanged.", "",
            "Each skill folder keeps its `SOURCES.md`, which credits the public repositories the skill was written from, with their licences. "
            f"Per-source credits and copyright lines: {REPO_URL}/blob/{ref}/CREDITS.md.", "",
            "If you change these files, the changes stay under CC BY-SA 4.0 (share-alike). Keep this notice and the licence copy with them. "
            "Your own code, and any file you write yourself, is not affected.", "",
            "Covered files: every file under these folders that starts with an `Installed from ai-sdlc-loop` comment, and the files in this folder.", "",
        ] + [f"- `{r}/`" for r in roots] + [f"- `{self.shared}/`", ""]
        if extras:
            lines += [f"The harness settings the script also wrote ({extras}) are ordinary project files under the project's licence.", ""]
        return "\n".join(lines)

    def plan(self):
        """{project-relative path: text} for everything this harness installs."""
        files = {}
        for item in self.items:
            files[item.dest] = self.render(item) if item.kind != "skill-sources" else self.render_sources(item)
        files[f"{self.shared}/LICENSE-CONTENT"] = (ROOT / "LICENSE-CONTENT").read_text(encoding="utf-8")
        files[f"{self.shared}/NOTICE.md"] = self.notice()
        for extra in self.h["extra_files"]:
            files[extra["path"]] = extra["text"] if "text" in extra else json.dumps(extra["json"], indent=2) + "\n"
        return files

    def render_sources(self, item):
        body = self.rewrite(item.body, item.src, item.dest)
        return self.provenance(item) + "\n\n" + body

    def check_names(self):
        problems = []
        seen = {}
        for item in self.items:
            if item.dest in seen:
                problems.append(f"{item.src} and {seen[item.dest]} would both install to {item.dest}")
            seen[item.dest] = item.src
            if item.kind in ("skill", "command") and item.dest.endswith("/SKILL.md"):
                name = item.values["name"]
                if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name) or len(name) > 64:
                    problems.append(f"{item.src}: skill name {name!r} is not 1-64 lower-case letters, digits and hyphens")
                if len(item.values["description"]) > 1024:
                    problems.append(f"{item.src}: description is longer than 1024 characters")
        return problems


def install(project, harness_id):
    inst = Installer(harness_id)
    problems = inst.check_names()
    if problems:
        raise SystemExit("\n".join(problems))
    project = Path(project)
    if not project.is_dir():
        raise SystemExit(f"{project} is not a folder")
    files = inst.plan()
    clashes = [p for p in files if (project / p).exists()]
    if clashes:
        raise SystemExit("Refusing to overwrite: " + ", ".join(sorted(clashes)))
    root = project.resolve()
    for rel, text in files.items():
        path = (project / rel).resolve()
        if not path.is_relative_to(root):
            raise SystemExit(f"{rel} is outside {project}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return inst, files


def main():
    args = sys.argv[1:]
    usage = __doc__.split("\n\n")[1]
    if args in (["-h"], ["--help"]):
        print(usage)
        return 0
    if args == ["--list"]:
        for h in load_harnesses()["harnesses"]:
            print(f"{h['id']}\t{h['name']}")
        return 0
    if len(args) == 2 and args[0] == "--validate":
        ids = [h["id"] for h in load_harnesses()["harnesses"]]
        return 0 if args[1] in ids else 1
    if len(args) != 2 or args[0].startswith("-"):
        print(usage, file=sys.stderr)
        return 2
    inst, files = install(args[0], args[1])
    print(f"Installed the {inst.h['name']} layout: {len(files)} files under {args[0]}. Notice: {inst.shared}/NOTICE.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
