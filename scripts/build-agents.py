#!/usr/bin/env python3
"""Regenerate agents/ and commands/ from data/skill-principle-map.json and the skills.

Usage:
  scripts/build-agents.py          write the files
  scripts/build-agents.py --check  exit 1 if any generated file is stale (for CI)

Standard library only. Every agent and command is built from the map by phase
and category, so the skills they load cannot drift from the map or the skills:

  - A phase loads the skills whose phase is that phase, plus the skills whose
    category is the phase's category (the category most of its skills are in).
  - agents/coordinator.md loads the Harness skills and can look up every principle.
  - agents/<phase>-producer.md loads, per skill, "When to use", the Do and Don't
    lists together, and "Steps".
  - agents/<phase>-reviewer.md loads, per skill, only the adversarial reviewer
    checks and the Don't list.
  - Every agent can also look up its skills' partial-overlap partners and the
    Harness skills.
  - commands/<name>.md loads the skills of the phases in COMMANDS.

Principle IDs are live IDs only. Retired IDs are resolved through "aliases" in
data/principles.json and must not appear in any generated file.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
AGENTS = ROOT / "agents"
COMMANDS_DIR = ROOT / "commands"
MARKER = "<!-- GENERATED by scripts/build-agents.py from data/skill-principle-map.json and skills/. Do not edit; edits are overwritten. -->"
ID_RE = re.compile(r"(?<![\d.])(\d+\.\d+)(?![\d])")

COORDINATOR_PHASE = "Harness"
# Every skill's reviewer section ends with this line; reviewers state it once in their rules.
VERDICT_LINE = "- Default verdict is FAIL until evidence shows otherwise; report findings to a file with P0-P3 severity."

ROLES = {
    "Harness": "harness engineer",
    "Plan": "planner",
    "Design": "architect",
    "Build": "implementer",
    "Verify": "tester",
    "Debug": "debugger",
    "Secure": "security engineer",
    "Review & ship": "release manager",
    "Learn": "learner",
}

# (command, phases in run order, what it is for, extra loop rule or None)
COMMANDS = [
    ("plan", ["Plan"], "Turn the brief into a spec and a plan with verifiable goals.", None),
    ("design", ["Design"], "Design the modules, contracts and decisions the plan needs.", None),
    ("build", ["Build"], "Implement the plan in small, safe steps that keep the build green.", None),
    ("verify", ["Verify", "Debug"], "Prove the build works with tests and evidence, and find the root cause of what fails.",
     "The Debug loop runs only when the Verify output shows failing behaviour (a failing test, a bug or an unexpected result), and only for those failures. Then run the Verify loop again on the fix."),
    ("review", ["Secure", "Review & ship"], "Review the change for security and quality before it ships.", None),
    ("ship", ["Review & ship"], "Get the reviewed change merged and released through the gates.", None),
    ("retro", ["Learn"], "Turn the human's end-of-cycle feedback into proposed skill and check edits.",
     "Run only after the human has given end-of-cycle feedback. The coordinator puts the proposed edits and their held-out results in its closing report for the human to approve (9.10). The Harness producer applies approved edits at the start of the next run, and every accepted or rejected edit is logged (9.12)."),
]

HARNESS_WHEN = "at the start of a run, to set up or check the project's agent harness, and when approved Learn edits are applied"

PHASE_NOTES = {
    "Harness": "Your work is the project's agent harness: the always-on rules file, skill descriptions, context loading and agent briefs. When the brief holds Learn edits, apply only the ones the human approved, each as one small edit.",
    "Learn": "Your input is the human's end-of-cycle feedback, passed on by the coordinator, with the run summary and the review files. For each piece of feedback, find the phase that failed, the Do or Don't rule at fault, and the smallest edit that would catch it next time. Propose edits; do not apply them. An edit goes live only after it passes on held-out cases and the human approves it, through the coordinator.",
}


def load(name):
    with open(DATA / name, encoding="utf-8") as f:
        return json.load(f)


def pid_key(pid):
    a, b = pid.split(".")
    return (int(a), int(b))


def slug(phase):
    return phase.lower().replace("&", "and").replace(" ", "-")


def yaml_list(items):
    return "[" + ", ".join(json.dumps(i, ensure_ascii=False) for i in items) + "]"


def sections(text):
    """Split a SKILL.md into {heading: body} on '## ' headings."""
    out, title, buf = {}, None, []
    for line in text.splitlines():
        if line.startswith("## "):
            if title is not None:
                out[title] = "\n".join(buf).strip()
            title, buf = line[3:].strip(), []
        elif title is not None:
            buf.append(line)
    if title is not None:
        out[title] = "\n".join(buf).strip()
    return out


def bullets(block):
    return [l for l in block.splitlines() if l.strip()]


class Skill:
    def __init__(self, entry, principle, errors):
        self.pid = entry["principle_id"]
        self.folder = entry["folder"]
        self.name = self.folder.split("/", 1)[1]
        self.phase = entry["phase"]
        self.category_id = entry["category_id"]
        self.statement = principle["statement"]
        self.overlap = principle["partial_overlap_with"]
        path = ROOT / self.folder / "SKILL.md"
        if not path.exists():
            errors.append(f"{self.pid}: {path.relative_to(ROOT)} missing")
            return
        secs = sections(path.read_text(encoding="utf-8"))
        reviewer = next((v for k, v in secs.items() if k.startswith("Adversarial reviewer")), None)
        producer = secs.get("Producer: dos and don'ts")
        if None in (reviewer, producer, secs.get("When to use"), secs.get("Steps")):
            errors.append(f"{self.folder}: needs When to use, Producer: dos and don'ts, Steps and Adversarial reviewer sections")
            return
        m = re.fullmatch(r"Do:\n(.+?)\n\s*Don't:\n(.+)", producer, re.S)
        if not m:
            errors.append(f"{self.folder}: Producer section must be a Do: list then a Don't: list")
            return
        self.when = secs["When to use"]
        self.dos, self.donts = bullets(m[1]), bullets(m[2])
        self.steps = bullets(secs["Steps"])
        self.checks = bullets(reviewer)
        if not self.checks or self.checks[-1] != VERDICT_LINE:
            errors.append(f"{self.folder}: reviewer section must end with {VERDICT_LINE!r}")
        else:
            self.checks = self.checks[:-1]


def build_model():
    pdoc, mdoc = load("principles.json"), load("skill-principle-map.json")
    errors = []
    aliases = pdoc["aliases"]
    principles = {p["id"]: p for p in pdoc["principles"]}
    skills = {}
    for e in mdoc["skills"]:
        pid = e["principle_id"]
        if pid in aliases:
            errors.append(f"map entry {e['folder']} uses retired id {pid}; use {aliases[pid]}")
            continue
        if pid not in principles:
            errors.append(f"map entry {e['folder']}: principle {pid} is not in principles.json")
            continue
        if e["folder"] != principles[pid]["skill_folder"]:
            errors.append(f"{pid}: map folder {e['folder']} differs from principles.json")
        for a in e["aliases"]:
            if aliases.get(a) != pid:
                errors.append(f"{pid}: map alias {a} does not resolve to {pid} in principles.json")
        if pid in skills:
            errors.append(f"{pid}: more than one skill in the map")
        skills[pid] = Skill(e, principles[pid], errors)
    if set(skills) != set(principles):
        errors.append("skill-principle-map.json and principles.json cover different principle ids")
    if errors:
        return None, errors

    phase_cat = {}
    for phase in {s.phase for s in skills.values()}:
        counts = Counter(s.category_id for s in skills.values() if s.phase == phase).most_common()
        if len(counts) > 1 and counts[0][1] == counts[1][1]:
            errors.append(f"phase {phase}: no single main category ({counts})")
        phase_cat[phase] = counts[0][0]
    if len(set(phase_cat.values())) != len(phase_cat):
        errors.append(f"two phases share a main category: {phase_cat}")
    order = sorted(phase_cat, key=lambda ph: (ph != COORDINATOR_PHASE, phase_cat[ph]))
    for ph in order:
        if ph not in ROLES:
            errors.append(f"phase {ph} has no role in ROLES")
    for name, phases, _, _ in COMMANDS:
        for ph in phases:
            if ph not in phase_cat:
                errors.append(f"/{name}: unknown phase {ph}")
    covered = {ph for _, phases, _, _ in COMMANDS for ph in phases} | {COORDINATOR_PHASE}
    for ph in order:
        if ph not in covered:
            errors.append(f"phase {ph} is not run by any command")
    if COORDINATOR_PHASE not in phase_cat:
        errors.append(f"coordinator phase {COORDINATOR_PHASE} is not in the map")
    if errors:
        return None, errors

    loads = {}
    for ph in order:
        ids = {pid for pid, s in skills.items() if s.phase == ph or s.category_id == phase_cat[ph]}
        loads[ph] = sorted(ids, key=pid_key)
    harness = set(loads[COORDINATOR_PHASE])
    lookup = {}
    for ph in order:
        ids = set(loads[ph]) | harness
        for pid in loads[ph]:
            if skills[pid].overlap:
                ids.add(skills[pid].overlap)
        ids |= {pid for pid, s in skills.items() if s.overlap in loads[ph]}
        lookup[ph] = sorted(ids, key=pid_key)
    loaded_somewhere = {pid for ids in loads.values() for pid in ids}
    if loaded_somewhere != set(skills):
        return None, ["skills loaded by no phase: " + ", ".join(sorted(set(skills) - loaded_somewhere, key=pid_key))]
    model = {
        "aliases": aliases, "skills": skills, "order": order, "phase_cat": phase_cat,
        "loads": loads, "lookup": lookup, "all_ids": sorted(skills, key=pid_key),
    }
    return model, []


def commands_for(phase):
    return [f"/{name}" for name, phases, _, _ in COMMANDS if phase in phases]


def producer_block(s):
    lines = [f"### {s.pid} {s.statement}", "",
             f"Skill: [{s.name}](../{s.folder}/SKILL.md)", "",
             f"When to use: {s.when}", "", "Do:"] + s.dos + ["", "Don't:"] + s.donts + ["", "Steps:"] + s.steps + [""]
    return lines


def reviewer_block(s):
    return [f"### {s.pid} {s.statement}", "", "Checks:"] + s.checks + ["", "Don't (the producer's list):"] + s.donts + [""]


def lookup_line(ids):
    return ", ".join(f"[{pid}](../principles/{pid}.md)" for pid in ids)


def front(fields):
    out = ["---"]
    for k, v in fields:
        out.append(f"{k}: {yaml_list(v) if isinstance(v, list) else v}")
    return out + ["---", MARKER, ""]


def render_producer(m, ph):
    sk = m["skills"]
    cmds = commands_for(ph)
    runs = ("Commands that start you: " + ", ".join(f"`{c}`" for c in cmds) + ".") if cmds else f"The coordinator starts you {HARNESS_WHEN}."
    lines = front([
        ("name", f"{slug(ph)}-producer"),
        ("description", json.dumps(f"Producer for the {ph} phase ({ROLES[ph]}). Started by the coordinator in a fresh context; does the {ph} work in its brief, applying each loaded skill's dos and don'ts together.")),
        ("role", "producer"),
        ("phase", json.dumps(ph)),
        ("commands", cmds),
        ("loads", ["When to use", "Producer: dos and don'ts", "Steps"]),
        ("skills", [sk[p].name for p in m["loads"][ph]]),
        ("principles", m["lookup"][ph]),
    ])
    lines += [
        f"# {ph} producer ({ROLES[ph]})", "",
        f"You do the {ph} work. The coordinator started you in a fresh context with a brief; a separate adversarial reviewer checks your work after you finish. {runs}", "",
    ]
    if ph in PHASE_NOTES:
        lines += [PHASE_NOTES[ph], ""]
    lines += [
        "## How you work", "",
        "- Work from the brief and the files it names. Load nothing else unless a step needs it (8.1).",
        "- Apply each skill below whose \"When to use\" fits the task. Its Do and Don't lists are one set of rules: follow both together.",
        "- Never contact the human. Where a skill below says to ask, escalate to or wait for the human, ask the coordinator instead. Look facts up yourself. Send a decision you cannot make to the coordinator with your recommended answer, carry on with that answer, and record it as an assumption.",
        "- Write your output, and a short report, to the files the brief names (8.8): what you did, the skill IDs you applied, your assumptions, and anything not done or not tested, with the reason.",
        "- On a later round you also get the reviewer's findings file. Fix each finding, or say in your report why it is wrong.", "",
        "## Skills you load", "",
        "From each skill's `SKILL.md`: When to use, the Do and Don't lists together, and Steps.", "",
    ]
    for pid in m["loads"][ph]:
        lines += producer_block(sk[pid])
    lines += [
        "## Principles you can look up", "",
        "Open `principles/<id>.md`, or the skill's `SKILL.md`, only when you need it. These are your skills, their partial-overlap partners and the Harness skills:", "",
        lookup_line(m["lookup"][ph]), "",
        "Use another principle only if the brief names it. Resolve any ID through `aliases` in [data/principles.json](../data/principles.json) first.", "",
    ]
    return "\n".join(lines)


