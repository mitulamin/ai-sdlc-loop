def check_ids(path, text, m, errors):
    body = text.split(MARKER, 1)[-1]
    retired = re.compile(r"(?<![\d.])(" + "|".join(re.escape(a) for a in m["aliases"]) + r")(?![\d])")
    for hit in retired.finditer(text):
        errors.append(f"{path}: retired id {hit[1]} (use {m['aliases'][hit[1]]})")
    for pid in ID_RE.findall(body):
        if pid not in m["skills"] and pid not in m["aliases"]:
            errors.append(f"{path}: names unknown principle {pid}")


def main():
    args = sys.argv[1:]
    if args not in ([], ["--check"]):
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    check = bool(args)
    m, errors = build_model()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    wanted = {AGENTS / "README.md": render_agents_index(m),
              AGENTS / "coordinator.md": render_coordinator(m),
              COMMANDS_DIR / "README.md": render_commands_index(m)}
    for ph in m["order"]:
        wanted[AGENTS / f"{slug(ph)}-producer.md"] = render_producer(m, ph)
        wanted[AGENTS / f"{slug(ph)}-reviewer.md"] = render_reviewer(m, ph)
    for name, phases, purpose, note in COMMANDS:
        wanted[COMMANDS_DIR / f"{name}.md"] = render_command(m, name, phases, purpose, note)
    for path, text in wanted.items():
        check_ids(path.relative_to(ROOT), text, m, errors)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    stale = []
    for path, text in wanted.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.parent.mkdir(exist_ok=True)
                path.write_text(text, encoding="utf-8")
    for d in (AGENTS, COMMANDS_DIR):
        for path in d.glob("*.md"):
            if path not in wanted and MARKER in path.read_text(encoding="utf-8"):
                stale.append(str(path.relative_to(ROOT)))
                if not check:
                    path.unlink()
    summary = f"{len(m['order'])} phases, {len(m['order']) * 2 + 1} agents, {len(COMMANDS)} commands"
    if check:
        if stale:
            print("Stale generated files: " + ", ".join(sorted(stale)), file=sys.stderr)
            print("Run scripts/build-agents.py and commit the result.", file=sys.stderr)
            return 1
        print(f"agents/ and commands/ are up to date ({summary})")
        return 0
    print(f"Wrote {len(stale)} file(s): {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
