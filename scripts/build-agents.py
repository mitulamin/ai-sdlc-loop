def render_command(m, name, phases, purpose, note):
    sk = m["skills"]
    ids = sorted({pid for ph in phases for pid in m["loads"][ph]}, key=pid_key)
    agents = [f"{slug(ph)}-{r}" for ph in phases for r in ("producer", "reviewer")]
    lines = front([
        ("description", json.dumps(f"{purpose} Runs the {' then '.join(phases)} loop{'s' if len(phases) > 1 else ''} with fresh-context producers and adversarial reviewers.")),
        ("argument-hint", json.dumps("<task, or path to the brief>")),
        ("phases", phases),
        ("agents", agents),
        ("skills", [sk[p].name for p in ids]),
    ])
    lines += [
        f"# /{name}", "",
        f"{purpose}", "",
        "For the coordinator. The human gives this command to the coordinator only; the coordinator runs the loop on its own and reports at the end of the cycle.", "",
        "Task: $ARGUMENTS", "",
        "## Loop", "",
        "For each phase, in order: " + ", ".join(phases) + ".", "",
        "1. Pick, from the phase's skills below, only the ones that apply to the task (1.8, 8.1). Write the brief to a file: the task, the acceptance criteria, the files to read, the skill IDs that apply, and where to write the output and the review.",
        "2. Start the phase's producer in a fresh context with the brief (8.7).",
        "3. Start the phase's reviewer in a fresh context with the brief's task and acceptance criteria and the producer's output, not its transcript or reasoning.",
        "4. On a reviewer FAIL, start a new producer with the brief and the findings file, then a new reviewer. After three FAILs in a row, stop the phase and record it as failed with its findings (5.5).",
        "5. On PASS, record the output and the review file for the coordinator's end-of-cycle report. Do not ask the human anything here.", "",
    ]
    if note:
        lines += [note, ""]
    lines += ["## Phases and the skills they load", ""]
    for ph in phases:
        lines += [f"### {ph}", "",
                  f"Producer: [{slug(ph)}-producer](../agents/{slug(ph)}-producer.md), which loads each skill's dos and don'ts together. "
                  f"Reviewer: [{slug(ph)}-reviewer](../agents/{slug(ph)}-reviewer.md), which loads only each skill's adversarial reviewer checks and don'ts.", ""]
        lines += [f"- [{sk[pid].name}](../{sk[pid].folder}/SKILL.md): {sk[pid].statement}" for pid in m["loads"][ph]]
        lines.append("")
    return "\n".join(lines)


