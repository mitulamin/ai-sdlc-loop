def load(name):
    with open(DATA / name, encoding="utf-8") as f:
        return json.load(f)


def pid_key(pid):
    a, b = pid.split(".")
    return (int(a), int(b))


def yaml_list(items):
    return "[" + ", ".join(json.dumps(i, ensure_ascii=False) for i in items) + "]"


def sections(text):
    """Split a SKILL.md into {heading: body} on '## ' headings."""
    out, title, buf = {}, None, []
    for line in text.splitlines():
        if line.startswith("## "):
            if title is not None:
                out[title] = "\n".join(buf).strip()
            title, buf = line[3:].strip(), []
        elif title is not None:
            buf.append(line)
    if title is not None:
        out[title] = "\n".join(buf).strip()
    return out


def bullets(block):
    return [l for l in block.splitlines() if l.strip()]


class Skill:
    def __init__(self, entry, principle, errors):
        self.pid = entry["principle_id"]
        self.folder = entry["folder"]
        self.name = entry["skill_name"]
        self.phase = entry["phase"]
        self.statement = principle["statement"]
        self.partners = [d["id"] for d in principle.get("distinct_from", [])]
        path = ROOT / self.folder / "SKILL.md"
        if not path.exists():
            errors.append(f"{self.pid}: {path.relative_to(ROOT)} missing")
            return
        secs = sections(path.read_text(encoding="utf-8"))
        reviewer = next((v for k, v in secs.items() if k.startswith("Adversarial reviewer")), None)
        producer = secs.get("Producer: dos and don'ts")
        if None in (reviewer, producer, secs.get("When to use"), secs.get("Steps")):
            errors.append(f"{self.folder}: needs When to use, Producer: dos and don'ts, Steps and Adversarial reviewer sections")
            return
        m = re.fullmatch(r"Do:\n(.+?)\n\s*Don't:\n(.+)", producer, re.S)
        if not m:
            errors.append(f"{self.folder}: Producer section must be a Do: list then a Don't: list")
            return
        self.when = secs["When to use"]
        self.dos, self.donts = bullets(m[1]), bullets(m[2])
        self.steps = bullets(secs["Steps"])
        self.checks = bullets(reviewer)
        if not self.checks or self.checks[-1] != VERDICT_LINE:
            errors.append(f"{self.folder}: reviewer section must end with {VERDICT_LINE!r}")
        else:
            self.checks = self.checks[:-1]

    @property
    def label(self):
        return f"{self.pid} {self.name}"


def build_model():
    pdoc, mdoc, tdoc = load("principles.json"), load("skill-principle-map.json"), load("taxonomy.json")
    cdoc = load("agent-contract.json")
    errors = []
    for label, doc in (("principles.json", pdoc), ("skill-principle-map.json", mdoc), ("taxonomy.json", tdoc),
                       ("agent-contract.json", cdoc)):
        if doc.get("schema_version") != SCHEMA_VERSIONS[label]:
            errors.append(f"{label}: schema_version is {doc.get('schema_version')!r}, this script expects {SCHEMA_VERSIONS[label]}")
    if errors:
        return None, errors
    principles = {p["id"]: p for p in pdoc["principles"] if p["status"] == "active"}
    aliases = {a: p["id"] for p in pdoc["principles"] for a in p.get("aliases", [])}
    skills = {}
    for e in mdoc["skills"]:
        pid = e["principle_id"]
        if pid in aliases:
            errors.append(f"map entry {e['folder']} uses retired id {pid}; use {aliases[pid]}")
            continue
        if pid not in principles:
            errors.append(f"map entry {e['folder']}: {pid} is not an active principle in principles.json")
            continue
        if pid in skills:
            errors.append(f"{pid}: more than one skill in the map")
            continue
        skills[pid] = Skill(e, principles[pid], errors)
    if set(skills) != set(principles):
        errors.append("skill-principle-map.json and principles.json cover different principle ids")
    if errors:
        return None, errors

    phases = sorted(tdoc["phases"], key=lambda ph: ph["order"])
    by_slug = {ph["slug"]: ph for ph in phases}
    if COORDINATOR_PHASE not in by_slug:
        errors.append(f"coordinator phase {COORDINATOR_PHASE} is not in data/taxonomy.json")
    elif by_slug[COORDINATOR_PHASE]["commands"]:
        errors.append(f"coordinator phase {COORDINATOR_PHASE} must have no commands in data/taxonomy.json")
    loads = {}
    for ph in phases:
        ids = sorted((pid for pid, s in skills.items() if s.phase == ph["slug"]), key=pid_key)
        if ids != sorted(ph["principles"], key=pid_key):
            errors.append(f"phase {ph['slug']}: data/taxonomy.json principles differ from the map's phase field")
        if not ids:
            errors.append(f"phase {ph['slug']}: no skills in the map")
        loads[ph["slug"]] = ids
    for pid, s in skills.items():
        if s.phase not in by_slug:
            errors.append(f"{pid}: phase {s.phase} is not in data/taxonomy.json")
    names = [ph[k] for ph in phases for k in ("producer_agent", "reviewer_agent")] + ["coordinator"]
    if len(set(names)) != len(names):
        errors.append(f"agent names in data/taxonomy.json are not unique: {names}")
    for n in names:
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", n) or n == "README":
            errors.append(f"agent name {n!r} is not a safe file name")
    tax_cmds = {c for ph in phases for c in ph["commands"]}
    for c in sorted(tax_cmds - set(COMMANDS)):
        errors.append(f"command /{c} is in data/taxonomy.json but has no purpose in COMMANDS")
    for c in sorted(set(COMMANDS) - tax_cmds):
        errors.append(f"command /{c} in COMMANDS runs no phase in data/taxonomy.json")
    for ph in phases:
        if ph["slug"] != COORDINATOR_PHASE and not ph["commands"]:
            errors.append(f"phase {ph['slug']} is not run by any command")
    rb = cdoc["output_field"]["request_block"]
    types = cdoc["register"]["types"]
    if set(rb["tag_meaning"]) != set(types):
        errors.append("agent-contract.json: request_block.tag_meaning must have exactly one entry per register type")
    if len(set(types)) != len(types) or any(not re.fullmatch(r"[a-z]+", t) for t in types):
        errors.append("agent-contract.json: register types must be unique lower-case words")
    if errors:
        return None, errors

    harness = set(loads[COORDINATOR_PHASE])
    lookup = {}
    for ph in phases:
        mine = set(loads[ph["slug"]])
        ids = mine | harness
        for pid in mine:
            ids |= set(skills[pid].partners)
        ids |= {pid for pid, s in skills.items() if mine & set(s.partners)}
        lookup[ph["slug"]] = sorted(ids, key=pid_key)
    commands = [(name, [ph for ph in phases if name in ph["commands"]], purpose, note)
                for name, (purpose, note) in COMMANDS.items()]
    model = {
        "aliases": aliases, "skills": skills, "phases": phases, "by_slug": by_slug,
        "loads": loads, "lookup": lookup, "all_ids": sorted(skills, key=pid_key), "commands": commands,
        "contract": cdoc,
    }
    return model, []


def commands_for(m, slug):
    return [f"/{c}" for c in m["by_slug"][slug]["commands"]]


def cmd_cell(m, slug):
    return ", ".join(f"`{c}`" for c in commands_for(m, slug)) or "coordinator"


def producer_block(s):
    return [f"### {s.pid} {s.statement}", "",
            f"Skill: [{s.label}](../{s.folder}/SKILL.md)", "",
            f"When to use: {s.when}", "", "Do:"] + s.dos + ["", "Don't:"] + s.donts + ["", "Steps:"] + s.steps + [""]


def reviewer_block(s):
    return [f"### {s.pid} {s.statement}", "", "Checks:"] + s.checks + ["", "Don't (the producer's list):"] + s.donts + [""]


def lookup_line(ids):
    return ", ".join(f"[{pid}](../principles/{pid}.md)" for pid in ids)


def front(fields):
    out = ["---"]
    for k, v in fields:
        out.append(f"{k}: {yaml_list(v) if isinstance(v, list) else v}")
    return out + ["---", MARKER, ""]


SECTION_PREFIX = "Required output field: "
REGISTER_ANCHOR = "README.md#the-shared-surface-register"


def cap(text):
    return text[:1].upper() + text[1:]


def field_key(m):
    return m["contract"]["output_field"]["key"]


def field_heading(m):
    return m["contract"]["output_field"]["heading"]


def register_flag(m):
    return m["contract"]["register"]["flag"]


def register_default(m):
    return m["contract"]["register"]["default_path"]


def request_block(m):
    rb = m["contract"]["output_field"]["request_block"]
    types = m["contract"]["register"]["types"]
    return [rb["header"]] + [f"[{t.upper()}: {rb['placeholder']}]" for t in types] + [rb["footer"]]


def request_block_lines(m):
    """The register-request template, fenced for display. Identical in every agent file."""
    return ["```text"] + request_block(m) + ["```", ""]


def type_meanings(m):
    rb = m["contract"]["output_field"]["request_block"]
    return [f"- `{t.upper()}`: {rb['tag_meaning'][t]}." for t in m["contract"]["register"]["types"]]


def cannot_write_instruction(m):
    return m["contract"]["output_field"]["request_block"]["cannot_write_instruction"]


def shell_less_reviewers(m):
    return [ph["reviewer_agent"] for ph in m["phases"] if ph["slug"] not in REVIEWERS_WITH_BASH]


def output_field_section(m, agent, phase, role, shell=True):
    """The required-output-field section of an agent file. role is producer, reviewer or coordinator."""
    c = m["contract"]
    rb = c["output_field"]["request_block"]
    heading, none = field_heading(m), c["output_field"]["none_text"]
    reg = c["register"]
    where = {"producer": "Every output file you write, your report included, ends",
             "reviewer": "Your findings file ends, after the findings,",
             "coordinator": "`run-summary.md` ends"}[role]
    lines = [f"## {SECTION_PREFIX}{heading}", "",
             f"{where} with a section headed `## {heading}`. {c['output_field']['rule']}", "",
             "In it, write a register-request block in exactly this format, without the code fence:", ""]
    lines += request_block_lines(m)
    lines += [f"{rb['line_rule']} {rb['verbatim_rule']}", ""] + type_meanings(m) + [""]
    if role == "reviewer":
        lines += ["Your own entries are what you assumed in order to review (for example, why you marked a check N/A or could not run it), questions about unclear acceptance criteria, and anything that blocks the review. "
                  f"The producer's output must end with the same section, with `{none}` if it has none: a producer's output without it is a P1 finding (skill ID 'other'). "
                  "A line in the register is a claim to read, not evidence.", ""]
    elif role == "coordinator":
        lines += ["Your entries are your own assumptions, questions and blockers. The curated list for the human, built from the register after your last pull (see below), goes in its own section above this one: what is still open, what the human answered, and what you decided yourself, each with its entry ID.", ""]
    else:
        lines += ["Say in the statement what is at stake if it matters and, for a question, your recommended answer. The coordinator rates impact and urgency when it curates.", ""]
    if role == "coordinator":
        lines += [f"The register is the shared surface agents write these entries to. Its path is the `{reg['flag']}` flag on the command the human gave, else `{reg['default_path']}`. Format: [agents/{REGISTER_ANCHOR}]({REGISTER_ANCHOR}).", ""]
    else:
        lines += [f"The shared surface register is where the entries go. The brief gives its path: the `{reg['flag']}` flag of the command (default `{reg['default_path']}`). "
                  f"It is append-only: never edit or delete a line. Format: [{REGISTER_ANCHOR}]({REGISTER_ANCHOR}).", ""]
        if shell:
            lines += [f'You can write to the register yourself. Once your output file is written, run `python scripts/register.py ingest <your output file> --register <path> --agent {agent} --phase "{phase}"`, which writes each statement in the block out verbatim. '
                      "If that script is not in your project, append one JSON line per entry yourself, with the statement as `text`, in the format linked above.", ""]
        else:
            lines += ["You cannot write to the register yourself, so you must emit the block. Put it in your findings file and repeat the same block, unchanged, as plain text in your final message, so it is in your transcript. "
                      "The coordinator takes it from there and writes it out verbatim.", ""]
    lines += [cannot_write_instruction(m), ""]
    if role == "coordinator":
        names = ", ".join(f"`{n}`" for n in shell_less_reviewers(m))
        lines += [f"Agents that you start with no `Bash` in their `tools` list ({names}), and any agent that tells you it cannot write to the register, are such agents. "
                  f'Take the block from its final message (or its findings file; not both) and run `python scripts/register.py ingest - --register <path> --agent <its name> --phase "<its phase>" --via coordinator` with the block on standard input. '
                  "Do not summarise, merge, reword, reorder, rate or drop a line, and do not ingest a block you wrote yourself in its place. Curate afterwards, with update lines only.", ""]
    return lines


def check_agent_contract(path, text, contract):
    """Return the problems with one agent file: it must declare the required output field and the instruction."""
    of = contract["output_field"]
    key, heading, rb = of["key"], of["heading"], of["request_block"]
    errs = []
    if not text.startswith("---\n") or "\n---\n" not in text[4:]:
        return [f"{path}: no front matter, so it cannot declare the required output field {key}"]
    front_text = text[4:text.index("\n---\n", 4)]
    line = next((l for l in front_text.splitlines() if l.startswith("output_fields:")), None)
    try:
        declared = json.loads(line.split(":", 1)[1]) if line else None
    except json.JSONDecodeError:
        declared = None
    if not isinstance(declared, list) or key not in declared:
        errs.append(f"{path}: front matter must declare output_fields containing {key!r}")
    start = text.find(f"\n## {SECTION_PREFIX}{heading}\n")
    if start < 0:
        errs.append(f"{path}: missing the section '## {SECTION_PREFIX}{heading}'")
        return errs
    nxt = text.find("\n## ", start + 1)
    section = text[start: nxt if nxt >= 0 else len(text)]
    if rb["cannot_write_instruction"] not in section:
        errs.append(f"{path}: the '{heading}' section lacks the instruction: {rb['cannot_write_instruction']!r}")
    template = [rb["header"]] + [f"[{t.upper()}: {rb['placeholder']}]" for t in contract["register"]["types"]] + [rb["footer"]]
    if "\n".join(template) not in section:
        errs.append(f"{path}: the '{heading}' section lacks the register-request block ({rb['header']} ... {rb['footer']}) with a [TYPE: ...] line for each type")
    return errs


def render_producer(m, ph):
    slug, name, role = ph["slug"], ph["name"], ph["role"]
    sk = m["skills"]
    cmds = commands_for(m, slug)
    runs = ("Commands that start you: " + ", ".join(f"`{c}`" for c in cmds) + ".") if cmds else f"The coordinator starts you {HARNESS_WHEN}."
    lines = front([
        ("name", ph["producer_agent"]),
        ("description", json.dumps(f"Producer for the {name} phase ({role}). Started by the coordinator in a fresh context; does the {name} work in its brief, applying each loaded skill's dos and don'ts together.")),
        ("role", "producer"),
        ("phase", json.dumps(name)),
        ("commands", cmds),
        ("loads", ["When to use", "Producer: dos and don'ts", "Steps"]),
        ("skills", m["loads"][slug]),
        ("principles", m["lookup"][slug]),
        ("output_fields", [field_key(m)]),
    ])
    lines += [
        f"# {name} producer ({role})", "",
        f"You do the {name} work. The coordinator started you in a fresh context with a brief; a separate adversarial reviewer, [{ph['reviewer_agent']}]({ph['reviewer_agent']}.md), checks your work after you finish. {runs}", "",
    ]
    if slug in PHASE_NOTES:
        lines += [PHASE_NOTES[slug], ""]
    lines += [
        "## How you work", "",
        "- Work from the brief and the files it names. Load nothing else unless a step needs it (8.1).",
        "- Apply each skill below whose \"When to use\" fits the task. Its Do and Don't lists are one set of rules: follow both together.",
        f"- Never contact the human. Where a skill below says to ask, escalate to or wait for the human, ask the coordinator instead. Look facts up yourself. Send a decision you cannot make to the coordinator, through the register, with your recommended answer, carry on with that answer, and record it as an assumption. Your output ends with the required `{field_heading(m)}` section (below).",
        f"- Write your output, and a short report, to the files the brief names (8.8): what you did, the skill IDs you applied, anything not done or not tested, with the reason, and the `{field_heading(m)}` section.",
        "- On a later round you also get the reviewer's findings file. Fix each finding, or say in your report why it is wrong.", "",
    ]
    lines += output_field_section(m, ph["producer_agent"], name, "producer")
    lines += [
        "## Skills you load", "",
        f"Skill IDs: {', '.join(m['loads'][slug])}. From each skill's `SKILL.md`: When to use, the Do and Don't lists together, and Steps.", "",
    ]
    for pid in m["loads"][slug]:
        lines += producer_block(sk[pid])
    lines += [
        "## Principles you can look up", "",
        "Open `principles/<id>.md`, or the skill's `SKILL.md`, only when you need it. These are your skills, the principles they are distinct from, and the Harness skills:", "",
        lookup_line(m["lookup"][slug]), "",
        "Use another principle only if the brief names it. Resolve any ID through `aliases` in [data/principles.json](../data/principles.json) first.", "",
    ]
    return "\n".join(lines)


