def render_command(m, name, phases, purpose, note):
    sk = m["skills"]
    ids = sorted({pid for ph in phases for pid in m["loads"][ph["slug"]]}, key=pid_key)
    names = [ph["name"] for ph in phases]
    agents = [ph[k] for ph in phases for k in ("producer_agent", "reviewer_agent")]
    lines = front([
        ("description", json.dumps(f"{purpose} Runs the {' then '.join(names)} loop{'s' if len(phases) > 1 else ''} with fresh-context producers and adversarial reviewers.")),
        ("argument-hint", json.dumps("<task, or path to the brief>")),
        ("phases", names),
        ("agents", agents),
        ("skills", ids),
    ])
    lines += [
        f"# /{name}", "",
        purpose, "",
        "For the coordinator. The human gives this command to the [coordinator](../agents/coordinator.md) only; the coordinator runs the loop on its own and reports at the end of the cycle.", "",
        "Task: $ARGUMENTS", "",
        "## Loop", "",
        "Phases, in order: " + ", ".join(names) + ".", "",
    ]
    if note:
        lines += [note, ""]
    lines += [
        "For each phase that runs:", "",
        "1. Pick, from the phase's skills below, only the ones that apply to the task (1.8, 8.1). Write the brief to a file: the task, the acceptance criteria, the files to read, the skill IDs that apply, and where to write the output and the review.",
        "2. Start the phase's producer in a fresh context with the brief (8.7).",
        "3. Start the phase's reviewer in a fresh context with the brief's task and acceptance criteria and the producer's output, not its transcript or reasoning.",
        "4. On a reviewer FAIL, start a new producer with the brief and the findings file, then a new reviewer. After three FAILs in a row, stop the phase and record it as failed with its findings (5.5).",
        "5. On PASS, record the output and the review file for the coordinator's end-of-cycle report. Do not ask the human anything here.", "",
        "## Phases and the skills they load", "",
    ]
    for ph in phases:
        lines += [f"### {ph['name']}", "",
                  f"Producer: [{ph['producer_agent']}](../agents/{ph['producer_agent']}.md), which loads each skill's dos and don'ts together. "
                  f"Reviewer: [{ph['reviewer_agent']}](../agents/{ph['reviewer_agent']}.md), which loads only each skill's adversarial reviewer checks and don'ts.", "",
                  f"Skill IDs: {', '.join(m['loads'][ph['slug']])}.", ""]
        lines += [f"- [{sk[pid].label}](../{sk[pid].folder}/SKILL.md): {sk[pid].statement}" for pid in m["loads"][ph["slug"]]]
        lines.append("")
    return "\n".join(lines)


