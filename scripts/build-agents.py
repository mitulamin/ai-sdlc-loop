def render_commands_index(m):
    coord = m["by_slug"][COORDINATOR_PHASE]
    lines = [MARKER, "", "# commands", "",
             "Slash commands for the main loop. The human gives them to the [coordinator](../agents/coordinator.md), which runs each phase's producer and adversarial reviewer on its own. "
             "Generated by `scripts/build-agents.py` from [data/taxonomy.json](../data/taxonomy.json) and [data/skill-principle-map.json](../data/skill-principle-map.json).", "",
             "| Command | Phases | What it is for | Skill IDs |", "| --- | --- | --- | --- |"]
    for name, phases, purpose, _ in m["commands"]:
        ids = sorted({pid for ph in phases for pid in m["loads"][ph["slug"]]}, key=pid_key)
        lines.append(f"| [/{name}]({name}.md) | {', '.join(ph['name'] for ph in phases)} | {purpose} | {', '.join(ids)} |")
    lines.append("")
    for ph in m["phases"]:
        cmds = commands_for(m, ph["slug"])
        if len(cmds) > 1:
            lines.append(f"There is one {ph['name']} phase, so {' and '.join(f'`{c}`' for c in cmds)} run the same {ph['name']} producer and reviewer, each on its own task.")
            lines.append("")
    lines += [f"The {coord['name']} skills have no command: the coordinator loads them, and starts the {coord['name']} producer and reviewer {HARNESS_WHEN}.", ""]
    return "\n".join(lines)


def check_ids(path, text, m, errors):
    body = text.split(MARKER, 1)[-1]
    if m["aliases"]:
        retired = re.compile(r"(?<![\w.])(" + "|".join(re.escape(a) for a in m["aliases"]) + r")(?!\d|\.\d)")
        for hit in retired.finditer(text):
            errors.append(f"{path}: retired id {hit[1]} (use {m['aliases'][hit[1]]})")
    for cite in re.finditer(r"\((\d+\.\d+(?:, \d+\.\d+)*)\)", body):
        for pid in cite[1].split(", "):
            if pid not in m["skills"] and pid not in m["aliases"]:
                errors.append(f"{path}: cites unknown principle {pid}")


def wanted_files(m):
    wanted = {AGENTS / "README.md": render_agents_index(m),
              AGENTS / "coordinator.md": render_coordinator(m),
              COMMANDS_DIR / "README.md": render_commands_index(m)}
    for ph in m["phases"]:
        wanted[AGENTS / f"{ph['producer_agent']}.md"] = render_producer(m, ph)
        wanted[AGENTS / f"{ph['reviewer_agent']}.md"] = render_reviewer(m, ph)
    for name, phases, purpose, note in m["commands"]:
        wanted[COMMANDS_DIR / f"{name}.md"] = render_command(m, name, phases, purpose, note)
    return wanted


def main():
    args = sys.argv[1:]
    usage = __doc__.split("\n\n")[1]
    if args in (["-h"], ["--help"]):
        print(usage)
        return 0
    if args not in ([], ["--check"]):
        print(usage, file=sys.stderr)
        return 2
    check = bool(args)
    m, errors = build_model()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    wanted = wanted_files(m)
    for path, text in wanted.items():
        check_ids(path.relative_to(ROOT), text, m, errors)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    stale = []
    for path, text in wanted.items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.parent.mkdir(exist_ok=True)
                path.write_text(text, encoding="utf-8")
    for d in (AGENTS, COMMANDS_DIR):
        for path in d.glob("*.md"):
            if path not in wanted and MARKER in path.read_text(encoding="utf-8").splitlines():
                stale.append(str(path.relative_to(ROOT)))
                if not check:
                    path.unlink()
    n = len(m["phases"])
    summary = f"{n} phases, {n * 2 + 1} agents, {len(m['commands'])} commands"
    if check:
        if stale:
            print("Stale generated files: " + ", ".join(sorted(stale)), file=sys.stderr)
            print("Run scripts/build-agents.py and commit the result.", file=sys.stderr)
            return 1
        print(f"agents/ and commands/ are up to date ({summary})")
        return 0
    print(f"Wrote {len(stale)} file(s): {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
