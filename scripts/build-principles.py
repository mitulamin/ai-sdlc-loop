#!/usr/bin/env python3
"""Regenerate principles/*.md from data/principles.json.

Usage:
  scripts/build-principles.py          write the files
  scripts/build-principles.py --check  exit 1 if any generated file is stale (for CI)

Standard library only. Hand-written notes for a principle live in
data/notes/principles/<id>.md and are appended under a Notes heading.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "principles"
NOTES = DATA / "notes" / "principles"
MARKER = "<!-- GENERATED by scripts/build-principles.py from data/principles.json. Do not edit; edits are overwritten. -->"
SCHEMA_VERSIONS = {"principles.json": "1.2.0", "sources.json": "1.0.0"}
ID_RE = re.compile(r"^(\d+)\.(\d+)$")


def load(name):
    with open(DATA / name, encoding="utf-8") as f:
        return json.load(f)


def validate(pdoc, sdoc):
    errors = []
    for label, doc in (("principles.json", pdoc), ("sources.json", sdoc)):
        expected = SCHEMA_VERSIONS[label]
        if doc.get("schema_version") != expected:
            errors.append(f"{label}: schema_version is {doc.get('schema_version')!r}, this script expects {expected}")
    cats = {c["slug"]: c for c in pdoc["categories"]}
    label_to_repo = {lab: r for r in sdoc["repos"] for lab in r["labels"]}
    seen = set()
    for p in pdoc["principles"]:
        pid = p["id"]
        m = ID_RE.match(pid)
        if not m:
            errors.append(f"{pid}: id must look like 1.1")
            continue
        if pid in seen:
            errors.append(f"{pid}: duplicate id")
        seen.add(pid)
        if p["category"] not in cats:
            errors.append(f"{pid}: unknown category {p['category']!r}")
        elif int(m[1]) != cats[p["category"]]["number"] or int(m[2]) != p["number"]:
            errors.append(f"{pid}: id does not match category number and number")
        for lab in p["sources"]:
            if lab not in label_to_repo:
                errors.append(f"{pid}: source label {lab!r} has no repo in sources.json labels")
        if p["status"] not in ("active", "merged", "dropped"):
            errors.append(f"{pid}: bad status {p['status']!r}")
        for mid in p["provenance"]["merged_from"]:
            if not ID_RE.match(mid):
                errors.append(f"{pid}: bad merged_from id {mid!r}")
        for alias in p.get("aliases", []):
            if not ID_RE.match(alias):
                errors.append(f"{pid}: bad alias {alias!r}")
    ids = {p["id"] for p in pdoc["principles"]}
    alias_owner = {}
    for p in pdoc["principles"]:
        for alias in p.get("aliases", []):
            if alias in ids:
                errors.append(f"{p['id']}: alias {alias} is also a live principle id")
            if alias in alias_owner:
                errors.append(f"{p['id']}: alias {alias} is already an alias of {alias_owner[alias]}")
            alias_owner[alias] = p["id"]
        for d in p.get("distinct_from", []):
            if d["id"] not in ids:
                errors.append(f"{p['id']}: distinct_from points at unknown principle {d['id']}")
    active = {p["id"] for p in pdoc["principles"] if p["status"] == "active"}
    practice_host = {}
    for p in pdoc["principles"]:
        for r in p.get("related_practices", []):
            if p["status"] != "active":
                errors.append(f"{p['id']}: only an active principle can carry related practices")
            if r["name"] in practice_host:
                errors.append(f"{p['id']}: related practice {r['name']!r} is already carried by {practice_host[r['name']]}")
            practice_host[r["name"]] = p["id"]
            if not (ROOT / r["guide"].partition("#")[0]).is_file():
                errors.append(f"{p['id']}: related practice {r['name']!r} links a guide that does not exist: {r['guide']}")
            for sid in r["see_also"]:
                if sid not in active or sid == p["id"]:
                    errors.append(f"{p['id']}: related practice {r['name']!r} has see_also {sid}, which is not another active principle")
    return errors, cats, label_to_repo


def related_skills(pid):
    return sorted(d.name for d in (ROOT / "skills").glob(f"{pid}-*") if d.is_dir())


def render(p, cats, label_to_repo):
    cat = cats[p["category"]]
    srcs = []
    for lab in p["sources"]:
        repo = label_to_repo[lab]
        srcs.append(f"[{lab}]({repo['url']})")
    skills = related_skills(p["id"])
    if skills:
        skill_lines = "\n".join(f"- [{s}](../skills/{s}/SKILL.md)" for s in skills)
    else:
        skill_lines = "Not written yet."
    prov = p["provenance"]
    lines = [
        MARKER,
        "",
        f"# Principle {p['id']}",
        "",
        f"> {p['statement']}",
        "",
        f"- Category: {cat['name']} ({cat['number']})",
        f"- Status: {p['status']}",
        f"- Sources: {', '.join(srcs)}",
        f"- Provenance: {prov['origin']}, {prov['research_run']}",
    ]
    if prov["merged_from"]:
        lines.append(f"- Merged from: {', '.join(prov['merged_from'])}")
    if prov["notes"]:
        lines.append(f"- Note: {prov['notes']}")
    if p.get("aliases"):
        lines.append("- Also known as: " + ", ".join(f"[{a}]({a}.md)" for a in p["aliases"]) + " (merged into this principle)")
    if p.get("distinct_from"):
        lines += ["", "## How it differs from related principles", ""]
        lines += [f"- [{d['id']}]({d['id']}.md): {d['difference']}" for d in p["distinct_from"]]
    if p.get("related_practices"):
        lines += ["", "## Related practices", "",
                  "Established practices this principle's skill applies too, each with a self-check item for the producer and a check for the reviewer:", ""]
        lines += [f"- [{r['name']}](../{r['guide']})" + (f". See also {', '.join(f'[{s}]({s}.md)' for s in r['see_also'])}." if r["see_also"] else "")
                  for r in p["related_practices"]]
    lines += ["", "## Skill", "", skill_lines, ""]
    note = NOTES / f"{p['id']}.md"
    if note.exists():
        lines += ["## Notes", "", note.read_text(encoding="utf-8").strip(), ""]
    return "\n".join(lines)


def render_alias(alias, target):
    return "\n".join([
        MARKER, "", f"# Principle {alias} (merged)", "",
        f"Principle {alias} was merged into [{target['id']}]({target['id']}.md): {target['statement']}", "",
        f"{target['provenance']['notes']} See [MERGES.md](../MERGES.md).", "",
    ])


def render_index(pdoc, cats):
    lines = [MARKER, "", "# Principles", "",
             "One file per principle. The list lives in [data/principles.json](../data/principles.json); these files are generated from it with `scripts/build-principles.py`.", ""]
    by_cat = {}
    for p in pdoc["principles"]:
        by_cat.setdefault(p["category"], []).append(p)
    for c in pdoc["categories"]:
        items = sorted(by_cat.get(c["slug"], []), key=lambda p: p["number"])
        lines += [f"## {c['number']}. {c['name']}", ""]
        for p in items:
            tag = "" if p["status"] == "active" else f" ({p['status']})"
            lines.append(f"- [{p['id']}]({p['id']}.md) {p['statement']}{tag}")
        lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    pdoc, sdoc = load("principles.json"), load("sources.json")
    errors, cats, label_to_repo = validate(pdoc, sdoc)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    wanted = {"README.md": render_index(pdoc, cats)}
    for p in pdoc["principles"]:
        wanted[f"{p['id']}.md"] = render(p, cats, label_to_repo)
        for alias in p.get("aliases", []):
            wanted[f"{alias}.md"] = render_alias(alias, p)
    OUT.mkdir(exist_ok=True)
    stale = []
    for name, text in wanted.items():
        path = OUT / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8")
    for path in OUT.glob("*.md"):
        if path.name not in wanted and path.read_text(encoding="utf-8").startswith(MARKER):
            stale.append(path.name)
            if not check:
                path.unlink()
    if check:
        if stale:
            print("Stale generated files: " + ", ".join(sorted(stale)), file=sys.stderr)
            return 1
        print(f"principles/ is up to date ({len(pdoc['principles'])} principles)")
        return 0
    print(f"Wrote {len(stale)} file(s) for {len(pdoc['principles'])} principles")
    return 0


if __name__ == "__main__":
    sys.exit(main())
