#!/usr/bin/env python3
"""Regenerate principles/*.md from data/principles.json and data/skill-principle-map.json.

Usage:
  scripts/build-principles.py          write the files
  scripts/build-principles.py --check  exit 1 if any generated file is stale (for CI)

Standard library only. principles/<id>.md is one file per live principle, in
the amalgamated-skills kit layout. Retired IDs are not given a file: they
resolve through the top-level "aliases" map in data/principles.json and are
listed on their survivor's page. principles/README.md is the generated index.
Hand-written notes for a principle live in data/notes/principles/<id>.md and
are appended under a Notes heading.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "principles"
NOTES = DATA / "notes" / "principles"
MARKER = "<!-- GENERATED by scripts/build-principles.py from data/principles.json. Do not edit; edits are overwritten. -->"
ID_RE = re.compile(r"^(\d+)\.(\d+)$")


def load(name):
    with open(DATA / name, encoding="utf-8") as f:
        return json.load(f)


def pid_key(pid):
    a, b = pid.split(".")
    return (int(a), int(b))


def validate(pdoc, mdoc):
    errors = []
    cats = {c["id"]: c for c in pdoc["categories"]}
    ids = [p["id"] for p in pdoc["principles"]]
    live = set(ids)
    if len(ids) != len(live):
        errors.append("duplicate principle ids")
    if pdoc.get("count") != len(ids):
        errors.append(f"count is {pdoc.get('count')}, but there are {len(ids)} principles")
    for p in pdoc["principles"]:
        pid = p["id"]
        m = ID_RE.match(pid)
        if not m:
            errors.append(f"{pid}: id must look like 1.1")
            continue
        cat = cats.get(p["category"])
        if not cat:
            errors.append(f"{pid}: unknown category {p['category']!r}")
        elif int(m[1]) != cat["id"] or p["category_name"] != cat["name"]:
            errors.append(f"{pid}: id or category_name does not match category {cat['id']}")
        if p["skill_folder"] != f"skills/{p['skill']}" or not p["skill"].startswith(pid + "-"):
            errors.append(f"{pid}: skill {p['skill']!r} and skill_folder {p['skill_folder']!r} disagree")
        if p["partial_overlap_with"] and p["partial_overlap_with"] not in live:
            errors.append(f"{pid}: partial_overlap_with points at unknown principle {p['partial_overlap_with']}")
    alias_map = pdoc["aliases"]
    listed = {}
    for p in pdoc["principles"]:
        for a in p["aliases"]:
            if a["id"] in listed:
                errors.append(f"{p['id']}: alias {a['id']} is already an alias of {listed[a['id']]}")
            listed[a["id"]] = p["id"]
    if listed != alias_map:
        errors.append(f"top-level aliases {alias_map} do not match the per-principle aliases {listed}")
    for old, new in alias_map.items():
        if old in live:
            errors.append(f"alias {old} is also a live principle id")
        if new not in live:
            errors.append(f"alias {old} -> {new}: survivor missing")
    by_pid = {}
    for s in mdoc["skills"]:
        if s["principle_id"] in by_pid:
            errors.append(f"{s['principle_id']}: more than one skill in skill-principle-map.json")
        by_pid[s["principle_id"]] = s
    if set(by_pid) != live:
        errors.append("skill-principle-map.json and principles.json cover different principle ids")
    for p in pdoc["principles"]:
        s = by_pid.get(p["id"])
        if not s:
            continue
        if s["folder"] != p["skill_folder"]:
            errors.append(f"{p['id']}: map folder {s['folder']} differs from skill_folder {p['skill_folder']}")
        if sorted(s["aliases"]) != sorted(a["id"] for a in p["aliases"]):
            errors.append(f"{p['id']}: map aliases {s['aliases']} differ from principles.json")
        if s["category_id"] != p["category"]:
            errors.append(f"{p['id']}: map category_id {s['category_id']} differs from principles.json")
    return errors, by_pid


def render(p, s, total):
    category = p["category_name"] + (f" / {p['subgroup']}" if p["subgroup"] else "")
    aliases = ", ".join(a["id"] for a in p["aliases"]) or "none"
    lines = [
        f"# {p['id']} {p['statement']}",
        "",
        f"- Category: {category}",
        f"- Amalgamated skill: [{p['skill']}](../{p['skill_folder']}/SKILL.md)",
        f"- Aliases: {aliases}",
        f"- Test: {s['test_app_name']}, {s['phase']}, slot {s['slot']} of {total}",
        f"- Licence status: {s['licence_status']}",
        "",
    ]
    if p["previous_statement"]:
        lines += [f"Previous wording: {p['previous_statement']}", ""]
    for a in p["aliases"]:
        lines += [f"Merged duplicate {a['id']}: {a['statement']}", ""]
    if p["partial_overlap_with"]:
        lines += [f"Partial overlap with {p['partial_overlap_with']}: kept as a separate principle.", ""]
    lines += [
        "## Source skills",
        "",
        f"{s['clean_sources']} licence-clean files; see [SOURCES.md](../{p['skill_folder']}/SOURCES.md).",
        "",
    ]
    note = NOTES / f"{p['id']}.md"
    if note.exists():
        lines += ["## Notes", "", note.read_text(encoding="utf-8").strip(), ""]
    return "\n".join(lines)


def render_index(pdoc):
    lines = [MARKER, "", "# Principles", "",
             "One file per principle. The list lives in [data/principles.json](../data/principles.json); these files are generated from it with `scripts/build-principles.py`.",
             "",
             "Retired IDs are aliases of their survivor: "
             + ", ".join(f"{old} is [{new}]({new}.md)" for old, new in pdoc["aliases"].items())
             + ". See [MERGES.md](../MERGES.md).",
             ""]
    for c in pdoc["categories"]:
        items = sorted((p for p in pdoc["principles"] if p["category"] == c["id"]), key=lambda p: pid_key(p["id"]))
        lines += [f"## {c['id']}. {c['name']}", ""]
        lines += [f"- [{p['id']}]({p['id']}.md) {p['statement']}" for p in items]
        lines.append("")
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    pdoc, mdoc = load("principles.json"), load("skill-principle-map.json")
    errors, by_pid = validate(pdoc, mdoc)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    total = len(pdoc["principles"])
    wanted = {"README.md": render_index(pdoc)}
    for p in pdoc["principles"]:
        wanted[f"{p['id']}.md"] = render(p, by_pid[p["id"]], total)
    OUT.mkdir(exist_ok=True)
    stale = []
    for name, text in wanted.items():
        path = OUT / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(name)
            if not check:
                path.write_text(text, encoding="utf-8")
    for path in OUT.glob("*.md"):
        if path.name not in wanted and (ID_RE.match(path.stem) or path.read_text(encoding="utf-8").startswith(MARKER)):
            stale.append(path.name)
            if not check:
                path.unlink()
    if check:
        if stale:
            print("Stale generated files: " + ", ".join(sorted(stale)), file=sys.stderr)
            return 1
        print(f"principles/ is up to date ({total} principles)")
        return 0
    print(f"Wrote {len(stale)} file(s) for {total} principles")
    return 0


if __name__ == "__main__":
    sys.exit(main())
